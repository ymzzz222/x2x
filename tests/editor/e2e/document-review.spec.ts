import { expect } from "@playwright/test";
import { test, sharedAvailable, origin, login, create, grant, activate, firstBlock, documentAction } from "./shared-document-fixture";

test.use({ channel: "chrome", viewport: { width: 1360, height: 900 } });
test.skip(!sharedAvailable, "Run against an isolated local preview and Supabase stack.");
test.setTimeout(100_000);

test("restoring a named version starts a new generation and keeps an older offline draft out of the restored document", async ({ provision }) => {
  const owner = await provision("owner");
  const editor = await provision("version-editor");
  await login(owner.page, owner.email);
  const path = await create(owner.page, "版本验收");
  await grant(owner.page, editor.email, "edit");
  await activate(owner.page);
  await owner.page.keyboard.insertText("版本一");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  const history = owner.page.getByRole("dialog", { name: "版本历史" });
  await documentAction(owner.page, "版本历史");
  await history.getByLabel("版本名称").fill("初稿");
  await history.getByRole("button", { name: "保存版本" }).click();
  await expect(history.getByRole("link", { name: "初稿" })).toBeVisible();
  const versionLink = await history.getByRole("link", { name: "初稿" }).getAttribute("href");
  await history.getByRole("button", { name: "关闭" }).click();

  await firstBlock(owner.page).locator(".tiptap").click();
  await owner.page.keyboard.insertText("后续");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  await login(editor.page, editor.email, path);
  await expect(firstBlock(editor.page)).toContainText("后续");
  await activate(editor.page);
  await editor.context.setOffline(true);
  await editor.page.keyboard.insertText("离线草稿");
  await expect(firstBlock(editor.page)).toContainText("离线草稿");

  await documentAction(owner.page, "版本历史");
  await expect(history.getByRole("link", { name: "初稿" })).toBeVisible();
  owner.page.once("dialog", (dialog) => dialog.accept());
  await history.getByRole("button", { name: "还原", exact: true }).click();
  await expect(firstBlock(owner.page)).toHaveText("版本一", { timeout: 20_000 });
  await editor.context.setOffline(false);
  await expect(editor.page.getByText(/本机保留了旧版本修改/)).toBeVisible({ timeout: 20_000 });
  await expect(firstBlock(editor.page)).toHaveText("版本一");
  await owner.page.goto(origin + versionLink);
  await expect(owner.page.getByRole("heading", { name: "版本验收 · 初稿" })).toBeVisible();
  await expect(owner.page.getByRole("group", { name: "文档模式" }).getByRole("button", { name: "编辑" })).toBeDisabled();
});

test("a viewer proposes a replacement and an editor applies it once to the anchored content", async ({ provision }) => {
  const owner = await provision("owner");
  const viewer = await provision("reviewer");
  await login(owner.page, owner.email);
  const path = await create(owner.page, "修订验收");
  await grant(owner.page, viewer.email, "view");
  await activate(owner.page);
  await owner.page.keyboard.insertText("Alpha");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  await login(viewer.page, viewer.email, path);
  await firstBlock(viewer.page).locator("[data-block-text]").dblclick({ position: { x: 8, y: 9 } });
  await documentAction(viewer.page, "修订");
  const viewerReview = viewer.page.getByRole("dialog", { name: "修订" });
  await viewerReview.getByLabel("建议替换文字").fill("Beta");
  await viewerReview.getByRole("button", { name: "提交修订" }).click();
  await expect(viewerReview.getByText("Beta", { exact: true })).toBeVisible();
  await expect(viewerReview.getByRole("button", { name: "接受修订" })).toHaveCount(0);
  await expect(firstBlock(owner.page)).toHaveText("Alpha");
  await documentAction(owner.page, "修订");
  const ownerReview = owner.page.getByRole("dialog", { name: "修订" });
  await ownerReview.getByRole("button", { name: "接受修订" }).click();
  await expect(ownerReview.getByRole("heading", { name: /已接受/ })).toBeVisible();
  await expect(ownerReview.getByRole("button", { name: "接受修订" })).toHaveCount(0);
  await expect(firstBlock(owner.page)).toHaveText("Beta");
  await expect(firstBlock(viewer.page)).toHaveText("Beta");
});

test("CO-07 rejecting, revising, replying to and withdrawing suggestions leaves the proposed text unchanged", async ({ provision }) => {
  const owner = await provision("reject-owner");
  const viewer = await provision("reject-viewer");
  await login(owner.page, owner.email);
  const path = await create(owner.page, "修订其他操作");
  await grant(owner.page, viewer.email, "view");
  await activate(owner.page);
  await owner.page.keyboard.insertText("Alpha");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  await login(viewer.page, viewer.email, path);
  const review = viewer.page.getByRole("dialog", { name: "修订" });
  const selection = firstBlock(viewer.page).locator("[data-block-text]");
  await selection.dblclick({ position: { x: 8, y: 9 } });
  await documentAction(viewer.page, "修订");
  await review.getByRole("button", { name: "提交修订" }).click();
  await expect(review.getByText("（删除）", { exact: true })).toBeVisible();
  await review.getByRole("button", { name: "关闭" }).click();

  await documentAction(owner.page, "修订");
  const ownerReview = owner.page.getByRole("dialog", { name: "修订" });
  await ownerReview.getByRole("button", { name: "拒绝修订" }).click();
  await expect(ownerReview.getByRole("heading", { name: /已拒绝/ })).toBeVisible();
  await expect(firstBlock(owner.page)).toHaveText("Alpha");
  await selection.dblclick({ position: { x: 8, y: 9 } });
  await documentAction(viewer.page, "修订");
  await review.getByLabel("建议替换文字").fill("Beta");
  await review.getByRole("button", { name: "提交修订" }).click();
  await expect(review.getByText("Beta", { exact: true })).toBeVisible();
  await review.getByRole("button", { name: "修改建议" }).click();
  await review.getByLabel("建议替换文字").fill("Gamma");
  await review.getByRole("button", { name: "提交修订" }).click();
  await expect(review.getByText("Gamma", { exact: true })).toBeVisible();
  await review.getByRole("button", { name: "回复修订" }).click();
  await review.getByLabel("回复内容").fill("确认撤回这条建议");
  await review.getByRole("button", { name: "发送修订回复" }).click();
  await expect(review.getByText(/确认撤回这条建议/)).toBeVisible();
  await review.getByRole("button", { name: "撤回建议" }).click();
  await expect(review.getByRole("heading", { name: /已撤回/ })).toBeVisible();
  await expect(review.getByRole("button", { name: "修改建议" })).toHaveCount(0);
  await viewer.page.reload();
  await expect(firstBlock(viewer.page)).toHaveText("Alpha");

  await selection.dblclick({ position: { x: 8, y: 9 } });
  await documentAction(viewer.page, "修订");
  await review.getByLabel("建议替换文字").fill("失效的建议");
  await review.getByRole("button", { name: "提交修订" }).click();
  await expect(review.getByText("失效的建议", { exact: true })).toBeVisible();
  await ownerReview.getByRole("button", { name: "关闭" }).click();
  await owner.page.reload();
  await activate(owner.page);
  await owner.page.keyboard.press("ControlOrMeta+a");
  await owner.page.keyboard.insertText("Unrelated");
  await expect(firstBlock(owner.page)).toHaveText("Unrelated");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  await documentAction(owner.page, "修订");
  await ownerReview.getByRole("button", { name: "接受修订" }).click();
  await expect(ownerReview.getByText("原文字或版本发生了变化，当前修订无法应用", { exact: true })).toBeVisible();
  await expect(firstBlock(owner.page)).toHaveText("Unrelated");
});

test("CO-08 a reader can compare and open snapshots but cannot create or restore versions", async ({ provision }) => {
  const owner = await provision("history-owner");
  const reader = await provision("history-reader");
  await login(owner.page, owner.email);
  const path = await create(owner.page, "历史比较");
  await grant(owner.page, reader.email, "view");
  await activate(owner.page);
  await owner.page.keyboard.insertText("保存的旧稿");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  await documentAction(owner.page, "版本历史");
  const ownerHistory = owner.page.getByRole("dialog", { name: "版本历史" });
  await ownerHistory.getByLabel("版本名称").fill("初始版本");
  await ownerHistory.getByRole("button", { name: "保存版本" }).click();
  await expect(ownerHistory.getByRole("link", { name: "初始版本" })).toBeVisible();
  await ownerHistory.getByRole("button", { name: "关闭" }).click();
  await firstBlock(owner.page).locator(".tiptap").press("End");
  await owner.page.keyboard.insertText("以及新稿");
  await expect(owner.page.getByText("云端已保存", { exact: true })).toBeVisible();
  await login(reader.page, reader.email, path);
  await expect(firstBlock(reader.page)).toHaveText("保存的旧稿以及新稿");
  await documentAction(reader.page, "版本历史");
  const history = reader.page.getByRole("dialog", { name: "版本历史" });
  await expect(history.getByRole("button", { name: "保存版本" })).toHaveCount(0);
  await expect(history.getByRole("button", { name: "还原", exact: true })).toHaveCount(0);
  await history.getByRole("button", { name: "比较正文" }).click();
  const diff = history.getByRole("region", { name: "正文版本差异" });
  await expect(diff.locator("del")).toHaveText("保存的旧稿");
  await expect(diff.locator("ins")).toHaveText("保存的旧稿以及新稿");
  await history.getByRole("link", { name: "初始版本" }).click();
  await expect(reader.page.getByRole("heading", { name: "历史比较 · 初始版本" })).toBeVisible();
  await expect(firstBlock(reader.page)).toHaveText("保存的旧稿");
  await expect(reader.page.getByRole("button", { name: "编辑", exact: true })).toBeDisabled();
});
